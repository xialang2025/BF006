#include "ds1302.h"
/*******************************************************************************
* 函 数 名         : Ds1302Write
* 函数功能		   : 向DS1302命令（地址+数据）
* 输    入         : addr,dat
* 输    出         : 无
*******************************************************************************/

u8 bcd2bin(u8 bv)
{
    return(bv>>4)*10+(bv&0x0f);
}

void Ds1302Write(u8 addr, u8 dat)
{
    TRISIO = 0;
	u8 n;
	RST = 0;
	NOP();

	SCLK = 0;//先将SCLK置低电平。
	NOP();
	RST = 1; //然后将RST(CE)置高电平。
	NOP();

	for (n=0; n<8; n++)//开始传送八位地址命令
	{
		DSIO = addr & 0x01;//数据从低位开始传送
		addr >>= 1;
		SCLK = 1;//数据在上升沿时，DS1302读取数据
		NOP();
		SCLK = 0;
		NOP();
	}
	for (n=0; n<8; n++)//写入8位数据
	{
		DSIO = dat & 0x01;
		dat >>= 1;
		SCLK = 1;//数据在上升沿时，DS1302读取数据
		NOP();
		SCLK = 0;
		NOP();	
	}	
		 
	RST = 0;//传送数据结束
	NOP();
    TRISIO = 1;
}

/*******************************************************************************
* 函 数 名         : Ds1302Read
* 函数功能		   : 读取一个地址的数据
* 输    入         : addr
* 输    出         : dat
*******************************************************************************/

u8 Ds1302Read(u8 addr)
{
	u8 n,dat,dat1;
    
	RST = 0;
	NOP();

	SCLK = 0;//先将SCLK置低电平。
	NOP();
	RST = 1;//然后将RST(CE)置高电平。
	NOP();
    TRISIO = 0;
	for(n=0; n<8; n++)//开始传送八位地址命令
	{
		DSIO = addr & 0x01;//数据从低位开始传送
		addr >>= 1;
		SCLK = 1;//数据在上升沿时，DS1302读取数据
		NOP();
		SCLK = 0;//DS1302下降沿时，放置数据
		NOP();
	}
    TRISIO = 1;
	NOP();
    
	for(n=0; n<8; n++)//读取8位数据
	{
		dat1 = DSIO;//从最低位开始接收
		dat = (dat>>1) | (dat1<<7);
		SCLK = 1;
		NOP();
		SCLK = 0;//DS1302下降沿时，放置数据
		NOP();
	}

	RST = 0;
	NOP();	//以下为DS1302复位的稳定时间,必须的。
	SCLK = 1;
	NOP();
	DSIO = 0;
	NOP();
	DSIO = 1;
	NOP();
	return dat;	
}