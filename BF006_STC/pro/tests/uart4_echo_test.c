#include "gpio.h"
#include "uart4.h"

/******************************************************************************
 * 函数名称       : main
 * 功能描述       : 通过串口四逐字节回显上位机发来的数据。
 * 输入参数       : None
 * 返回值         : None
 * 日期            : 2026.11.14
 ******************************************************************************/
void main(void) //20261114-0 add
{
    u8 received;

    EA = 0;               // 轮询收发标志，避免由串口中断提前清除
    GPIO_Init();          // 使用板上原有引脚配置，继电器初始化为关闭
    uart_init();          // 沿用串口四的九千六百波特和八位数据模式
    S4_Int_Disable();     // 串口四的收发标志由本测试程序处理
    CLR_TI4();

    for (;;) {
        if (RI4) {
            received = S4BUF; // 读取原始字节，包括零和不可打印字符
            CLR_RI4();
            S4BUF = received; // 原样发回收到的字节
            while (!TI4) {
                // 等待当前字节发完，再处理下一个字节
            }
            CLR_TI4();
        }
    }
}
